import { fileURLToPath, URL } from "node:url";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { resolve } from "node:path";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { defineConfig, type Plugin } from "vite";
import { build as bundleWorker } from "esbuild";

// Generate the worker from the actual output so lazy-loaded chunks are included
// and every build gets a content-based cache version without another dependency.
function batgramPwa(): Plugin {
  let publicDir: string;
  const notificationWorker = async () => {
    const output = await bundleWorker({
      entryPoints: [fileURLToPath(new URL("./worker/notifications.js", import.meta.url))],
      bundle: true, write: false, format: "iife", platform: "browser", target: "es2022", minify: true,
    });
    return output.outputFiles[0].text;
  };
  return {
    name: "batgram-pwa",
    enforce: "post",
    configResolved(config) {
      publicDir = config.publicDir;

    },
    configureServer(server) {
      // Development registers only on the dashboard; it has push handlers, no asset cache.
      server.middlewares.use("/sw.js", (_req, res) => {
        void notificationWorker().then((code) => {
          res.setHeader("Content-Type", "application/javascript");
          res.setHeader("Cache-Control", "no-cache");
          res.end(code + '\nself.addEventListener("activate", e => e.waitUntil(self.clients.claim()));');
        }).catch(() => { res.statusCode = 503; res.end(); });
      });
    },
    async generateBundle(_options, bundle) {
      const pushWorker = await notificationWorker();
      const hash = createHash("sha256");
      const urls: string[] = [];
      for (const name of Object.keys(bundle).sort()) {
        const file = bundle[name];
        if (name.endsWith(".map")) continue;
        hash.update(name).update(file.type === "chunk" ? file.code : file.source);
        urls.push(`/${name}`);
      }
      for (const file of readdirSync(publicDir, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => resolve(entry.parentPath, entry.name))
        .sort()) {
        const url = `/${file.slice(publicDir.length + 1).replaceAll("\\", "/")}`;
        hash.update(url).update(readFileSync(file));
        urls.push(url);
      }
      hash.update(pushWorker);
      const version = hash.digest("hex").slice(0, 16);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: `${pushWorker}\n/* BatGram production service worker. Generated by Vite. */
const CACHE = "batgram-static-${version}";
const PRECACHE = ${JSON.stringify(urls)};
const STATIC_URLS = new Set(PRECACHE);

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
  // Wait for existing app windows to close before activating an update.
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith("batgram-static-") && name !== CACHE).map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  // API, sockets, authentication, and private responses are never cached.
  if (request.method !== "GET" || url.origin !== self.location.origin || url.pathname.startsWith("/api/") || url.pathname.startsWith("/socket.io/") || url.pathname.startsWith("/chat/")) return;
  if (request.mode === "navigate") {
    event.respondWith(fetch(request).catch(() => caches.open(CACHE).then((cache) => cache.match("/offline.html"))));
    return;
  }
  if (url.search || !STATIC_URLS.has(url.pathname)) return;
  event.respondWith(caches.open(CACHE).then(async (cache) => (await cache.match(request)) || fetch(request)));
});
`,
      });
    },
  };
}

export default defineConfig({
  plugins: [react(), tailwindcss(), batgramPwa()],
  resolve: { alias: { "@": fileURLToPath(new URL("./src", import.meta.url)) } },
  build: {
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (/\/node_modules\/(react|react-dom|scheduler)\//.test(id))
            return "react-vendor";
        },
      },
    },
  },
  server: { strictPort: true },
});
